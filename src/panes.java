    private void jButtonCalcular1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCalcular1ActionPerformed
        // TODO add your handling code here:

        Double precioU = 0.0;

        switch (jComboBox1.getSelectedIndex()) {
            case 1:
                precioU = 2500.0;
                break;
            case 2:
                precioU = 1800.0;
                break;
            case 3:
                precioU = 2000.0;
                break;
            case 4:
                precioU = 700.0;
                break;
            case 5:
                precioU = 1000.0;
                break;
            case 6:
                precioU = 1600.0;
                break;
            case 7:
                precioU = 1250.0;
                break;

            default:
                JOptionPane.showMessageDialog(null, "Seleccione su producto(s)");
        }

        int cantidad = Integer.parseInt(jTextFieldCantidadReal.getText());
        Double precioTotal = precioU * cantidad;
        jTextFieldTotalReal.setText(String.valueOf(precioTotal));

        String texto = jComboBox1.getSelectedItem() + " | " + cantidad + " | " + precioTotal;

        Informe informe = new Informe();
        Total += precioTotal;
        informacion = informacion + "\n" + texto;

    }//GEN-LAST:event_jButtonCalcular1ActionPerformed

